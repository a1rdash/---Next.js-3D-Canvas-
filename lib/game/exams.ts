const VIN_ALPHABET = 'ABCDEFGHJKLMNPRSTUVWXYZ0123456789'

export function randomVin(): string {
  return Array.from({ length: 17 }, () => pick([...VIN_ALPHABET])).join('')
}

function brokenVin(): string {
  const vin = randomVin().split('')
  const kind = randInt(0, 2)
  if (kind === 0) {
    vin[randInt(0, 16)] = pick(['I', 'O', 'Q'])
    return vin.join('')
  }
  if (kind === 1) return vin.slice(0, 16).join('')
  return vin.join('') + pick([...VIN_ALPHABET])
}

function vinQuestion(): Omit<ExamQuestion, 'id'> {
  const bad = brokenVin()
  const options = shuffle([bad, randomVin(), randomVin(), randomVin()])
  return {
    prompt: 'Найди НЕДЕЙСТВИТЕЛЬНЫЙ VIN:',
    options,
    correct: options.indexOf(bad),
    explanation: 'Проверяй длину (17) и запрещённые буквы I, O, Q.',
  }
}

/** Перемешивает варианты ответа и пересчитывает индекс верного — верный ответ не всегда на одной и той же позиции */
function shuffleOptions<T extends { options: string[]; correct: number }>(q: T): T {
  const order = shuffle(q.options.map((_, i) => i))
  return { ...q, options: order.map((i) => q.options[i]), correct: order.indexOf(q.correct) }
}

export function buildExam(level: number): ExamQuestion[] {
  const pool = STATIC_QUESTIONS[Math.min(level, STATIC_QUESTIONS.length - 1)]
  const statics = shuffle(pool).slice(0, 4)
  const base = shuffle([...statics, vinQuestion()])
  // перемешиваем ответы; следим, чтобы верные ответы стояли минимум на трёх разных позициях
  let out = base.map(shuffleOptions)
  for (let tries = 0; tries < 12 && new Set(out.map((q) => q.correct)).size < Math.min(3, out.length); tries++) out = base.map(shuffleOptions)
  return out.map((q, i) => ({ ...q, id: `${level}-${i}` }))
}
